"""Expand the evidence knowledge base from authoritative public APIs.

Sources used by this script:
    - PubMed E-utilities (NCBI)
    - Europe PMC REST API
    - ClinicalTrials.gov Data API v2

The script never invents article URLs. URLs are generated by the existing
ingest adapters from returned PMID/NCT/Europe PMC identifiers.

Run from the evidence-assistant-mvp directory:
    python scripts/expand_kb.py --target-chunks 500
"""

