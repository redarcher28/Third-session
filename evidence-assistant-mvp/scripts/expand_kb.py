    'diabetes mellitus, type 2[MeSH Terms] AND diet therapy[MeSH Terms] AND cardiovascular diseases[MeSH Terms] AND hasabstract[text]',
    'diabetes mellitus, type 2[MeSH Terms] AND lifestyle[Title/Abstract] AND cardiovascular risk[Title/Abstract] AND hasabstract[text]',
    'diet, mediterranean[MeSH Terms] AND cardiovascular diseases[MeSH Terms] AND (systematic review[Title/Abstract] OR randomized controlled trial[Publication Type]) AND hasabstract[text]',
